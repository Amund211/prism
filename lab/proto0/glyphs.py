GLYPHS: dict[str, np.ndarray] = {}
for line in _RAW.strip().splitlines():
    ch, *rows = line.split()
    GLYPHS[ch] = np.array([[c == "#" for c in r] for r in rows], dtype=np.float32)
UNKNOWN = np.ones((8, 5), dtype=np.float32) * 0.4  # chars we did not draw


def render(text: str) -> np.ndarray:
    """8 x width bitmap (GUI px) of text, 1 px gap between glyphs."""
    cols = []
    for ch in text:
        g = GLYPHS.get(ch, UNKNOWN)
        cols += [g, np.zeros((8, 1), dtype=np.float32)]
    return np.concatenate(cols[:-1], axis=1) if cols else np.zeros((8, 0))
